# -*- coding: utf-8 -*-
"""Bundle the study material in data/ into web/data.js (inlined constants).

Why the web app does not fetch the JSON directly:
- when index.html is opened locally over file://, fetch is blocked by the
  browser CORS policy;
- inlined as data.js the same files work offline on a phone, opened locally
  and on GitHub Pages.

Generated globals:
    window.VOCAB     <- data/vocabulary.json  words[]
    window.LEZEN     <- data/lezen.json       passages[]
    window.ZINNEN    <- data/zinnen.json      sentences[]

Run after updating the material:
    python3 tools/build_web_data.py
"""

import os
import json

BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA_DIR = os.path.join(BASE_DIR, "data")
OUT = os.path.join(BASE_DIR, "web", "data.js")

# (global name, file name, top-level JSON key, label)
SOURCES = [
    ("VOCAB", "vocabulary.json", "words", "words"),
    ("LEZEN", "lezen.json", "passages", "reading passages"),
    ("ZINNEN", "zinnen.json", "sentences", "sentences"),
]


def load(filename, key):
    path = os.path.join(DATA_DIR, filename)
    if not os.path.exists(path):
        return []
    with open(path, "r", encoding="utf-8") as f:
        data = json.load(f)
    items = data.get(key, [])
    if not isinstance(items, list):
        raise ValueError("%s in %s is not an array" % (key, filename))
    return items


def main():
    parts = [
        "// This file is generated by tools/build_web_data.py - do not edit by hand.\n",
        "// Edit data/*.json and run the script again instead.\n",
    ]
    summary = []
    for var, filename, key, label in SOURCES:
        items = load(filename, key)
        payload = json.dumps(items, ensure_ascii=False, indent=1)
        parts.append("window.%s = %s;\n" % (var, payload))
        summary.append("%d %s" % (len(items), label))

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("".join(parts))
    print("Generated %s" % OUT)
    print("Contents: " + ", ".join(summary))


if __name__ == "__main__":
    main()